import argparse

parser=argparse.ArgumentParser()
parser=argparse.ArgumentParser(
    description='$ python vel2temp.py -v VELOCITY_FILE -a ATOM -e ENERGY_FILE -t "b", "mp"> OUTPUT')
parser.add_argument('-v', '--velocity_file', help='File with atomic velocities generated by tra2vel.py',type=str)
parser.add_argument('-a', '--atom', help='Atomic symbol of the element of interest',type=str)
parser.add_argument('-e', '--energy_file', help='Energy file generated by CPMD',type=str)
parser.add_argument('-t', '--temperature', help='Method for temperature.  The options are: b, to get it fitting a MB distribution; mp, to calculate it from the most frequent velocity; and mean, to calculate the temperature from the mean velocity',type=str)
args=parser.parse_args()
velocity_file=str(args.velocity_file)
element=str(args.atom)
energy_file=str(args.energy_file)
TempMet=str(args.temperature)

in_file = list()
input_file = open(velocity_file, 'r')
for i in input_file:
        in_file.append(i.replace('\n',''))
input_file.close()

atoms =int(in_file[0]) # total amount of atoms
steps=int(len(in_file)/(atoms+2))

#### List of atomic masses #############
Da_me=1822.888486209
atomic_mass={
'H': 1,
'He': 4.,
'Li': 7.,
'Be': 9.,
'B': 11.,
'C': 12.,
'N': 14.,
'O': 16.,
'F': 19.,
'Ne': 20.,
}
if element == 'water':
        element='O'
        atomic_mass[element]=18.

#### Save matrix of velocities of the specified element ####
velocity_matrix=list()
kinetic_energy=list()
for step in range (steps):
        velocity_list=list()
        kin_ene=0
        for atom in range (atoms):
                line=in_file[step*(atoms+2)+(atom+2)].split()
                kin_ene+=atomic_mass[line[0]]*Da_me*float(line[1])**2/2
                if line[0]==element:
                        velocity_list.append(float(line[1]))
        kinetic_energy.append(kin_ene) 
        velocity_matrix.append(velocity_list)
if len(velocity_matrix[0])==0:
        print ('The element '+element+' is not in this file :(')
        exit()
in_file=list()

#### Fit MB distribution and calculate temperature ####
import numpy as np
import matplotlib.pyplot as plt
import scipy.stats as stats

maxwell = stats.maxwell

vel_matrix=np.array(velocity_matrix)	# shape=(steps, #of atoms)
velocity_matrix=list()
atoms=len(vel_matrix[0])		# update #of atoms
vel_max=np.amax(vel_matrix)

m_k=atomic_mass[element]*Da_me/3.166811563e-6    #m*me/k
Temp=np.zeros((steps,2))

#### Fit MB distribution and calculate temperature ####
if TempMet == 'b':		# In Maxwell-Boltzmann distribution, b=m/2kT
        for i in range(steps):
                dist_fit=maxwell.fit(vel_matrix[i], floc=0)  #output parameter a =sqrt(kT/m)
                Temp[i][0]=(i+1)
                Temp[i][1]=(dist_fit[1]**2*m_k*3/2)	#T=a^2*m/k*3

#### Calculate temperature from the most probable (or repeated) velocity ####
elif TempMet == 'mp':
        from scipy.stats import mode
        vel_N=11
        for i in range(steps):
                step_norm=vel_matrix[i]/max(vel_matrix[i])
                norm_mode=mode(np.around(step_norm*vel_N/100,2))
                v_mp=norm_mode[0]*100/vel_N*max(vel_matrix[i])
                Temp[i][0]=(i+1)
                Temp[i][1]=(m_k*v_mp**2/2)*3	# T=(mv^2)/(2k)*3

#### Calculate temperature from the mean velocity ####
elif TempMet == 'mean':
        for i in range(steps):
                dist_fit=maxwell.fit(vel_matrix[i], floc=0)  #output parameter a =kT/m
                v_mean=maxwell.mean(*dist_fit)
                Temp[i][0]=(i+1)
                Temp[i][1]=(v_mean**2*3.1415926535*m_k/8)*3	# T=(pi*m*v^2)/(8k)

