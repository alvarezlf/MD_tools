#### Generate energy file with the aditional column ####
ene_file = open(energy_file, 'r')

ene_lines=list()
for i in range (10):
        ene_lines.append(ene_file.readline())
T_index=0

for line in ene_file:
        ene_lines=list()
        ene_lines.append(line.replace('\n','').split())
        while ene_lines[-1][0][-1]!='0':
                ene_lines.append(ene_file.readline().replace('\n','').split())
        data_out=np.zeros((10,1))
        for i in ene_lines:
                data_out[1]+=float(i[1])
                data_out[2]+=float(i[2])
                data_out[3]+=float(i[3])
                data_out[4]+=float(i[4])
                data_out[5]+=float(i[5])
                data_out[8]+=float(i[6])
                data_out[9]+=float(i[7])
        data_out=data_out/len(ene_lines)
        data_out[0]=ene_lines[0][0]
        data_out[6]=Temp[T_index][1]
        data_out[7]=kinetic_energy[T_index]
        T_index+=1
        text=' '*(8-len(str(int(data_out[0][0]))))+str(int(data_out[0][0]))	# Col 1
        text+=' '*(12-len(str(round(data_out[1][0],8))))+str(round(data_out[1][0],8))	# Col 2
        text+=' '*(10-len(str(round(data_out[2][0],3))))+str(round(data_out[2][0],3))	# Col 3
        text+=' '*(18-len(str(round(data_out[3][0],10))))+str(round(data_out[3][0],10))	# Col 4
        text+=' '*(18-len(str(round(data_out[4][0],10))))+str(round(data_out[4][0],10))	# Col 5
        text+=' '*(18-len(str(round(data_out[5][0],10))))+str(round(data_out[5][0],10))	# Col 6
        text+=' '*(12-len(str(round(data_out[6][0],3))))+str(round(data_out[6][0],3))	# Boltzmann Temperature
        text+=' '*(18-len('{:.8e}'.format(data_out[7][0])))+'{:.8e}'.format(data_out[7][0])
        text+=' '*(14-len('{:.5e}'.format(data_out[8][0])))+'{:.5e}'.format(data_out[8][0])
        text+=' '*(8-len(str(round(data_out[9][0],2))))+str(round(data_out[9][0],2))
        print(text)
